"""亲密事件识别：关系往上跨一级的唯一合法理由。

为什么需要这个模块
------------------
方案 §7.1 定下的规矩是「亲密值只能由事件触发，刷轮数没用」——这条规矩本身
是对的（否则聊一百句就死心塌地，关系变化变得毫无重量）。但规矩只写了一半：
`EmotionEngine.note_intimacy_event()` 是亲密值唯一的写入口，而全仓没有任何
地方调用它。

结果是亲密值永远停在初始的 20，而五个阶段的门槛是 15 / 40 / 65 / 85：

    冷淡 0 · 破冰 15 · 依赖 40 · 占有 65 · 病娇 85

也就是说「依赖」及之后三个阶段（占五分之三）在真实链路上**永远到不了**。
实测对照：连续 30 个自然日、每天 20 轮最正向的对话（「谢谢你，你真好，
我最喜欢你了，想你」），好感与信任都顶到 100，亲密值仍是 20，阶段死锁在
「破冰」。「关系会变」这条产品理念在引擎侧等于不存在。

本模块只做一件事：从用户这句话里认出「这算不算一次亲密事件」。
认出之后仍由情感引擎做冷却去重与数值加成。

判定口径：宁缺勿滥
------------------
认不准就不给。宁可关系推进得慢一点，也不要因为一句「你好」就跨段——
跨段是产品里最贵的信号，贬值一次就再也贵不起来了。
"""

from __future__ import annotations

import re

# 每条规则 =（事件类型，写进状态的说明，匹配式）
# 事件类型用于同类冷却：同一类事件 24 小时内只记一次。
_EVENT_RULES: list[tuple[str, str, re.Pattern[str]]] = [
    # 告白：必须是他主动说的「我喜欢你/我爱你」，不是夸她好看。
    # 后面紧跟「说的/的话/这样」时是在夸某句话、某种做法，不是告白，必须挡掉。
    ("confess", "他说他喜欢你",
     re.compile(r"我(?:真的|最|很|好|挺|永远|一直|特别)?(?:喜欢|爱)你"
                r"(?!说的|的话|这样|这种|刚才|说话)")),
    # 约定：拉钩、说定、保证——中文里最典型的「关系口头契约」
    ("promise", "你们拉了钩", re.compile(r"拉钩|说定了|一言为定|我保证")),
    # 长期承诺：留下、不走、一直在。
    # 中文里「一直在」有三种常见说法，第一版只覆盖了「留在/陪着」，实测漏掉
    # 「我们会一直在一起」与「我永远陪着你」两句最典型的告白——补成三个分支：
    #   ① 永远/一直 +（和你）+ 在一起   ② 永远/一直 + 陪着/陪在 + 你
    #   ③ 永远/一直 + 留在/在 + 你身边
    # 三个分支都要求「我」紧跟修饰语，所以「我们一起吃饭」「我跟她在一起」
    # 这类普通叙述不会被误认（修饰语至少要一个，否则不进这条规则）。
    ("stay", "他说他不会走",
     re.compile(r"我(?:们)?(?:会|要|想)?(?:"
                r"(?:永远|一直)+(?:和|跟)?你?在一起"
                r"|(?:永远|一直)*(?:留在|陪着|陪在)你?"
                r"|(?:留(?:在|下)?你?身边|(?:永远|一直)+在你?身边)"
                r"|不(?:会|想)?(?:走|离开你)"
                r")")),
    # 共同经历：约好「一起」做某件事（限第一/第二人称，排除「大家一起」）
    # 「咱们」是口语里最常见的自称双数，第一版漏了它。
    ("together", "你们约好了一起做事", re.compile(r"(?:我们|咱们|下次|跟我|咱俩)一起")),
    # 赠礼：送了、买了东西给她。中文里两种语序都要认（"送你" / "给你买了"），
    # 而「送你回去/去上班」是接送不是礼物，用后向断言排除。
    ("gift", "他送了东西给你",
     re.compile(r"(?:(?:送|买|带)(?:了|给)?你|给你(?:买|带)了)(?!回|去|上班|上学|到家)")),
    # 和好：道歉与认错同时出现，才算「把话说开了」而不是随口一句对不起
    ("reconcile", "你们把话说开了", re.compile(r"对不起.{0,8}我错了|我错了.{0,8}对不起")),
]

# 否定词：紧挨在动眼前面时语义反转（「我不送你」不是赠礼）
_NEGATORS = "不没别无非勿"


def detect(text: str) -> tuple[str, str] | None:
    """认出一句话里的第一次亲密事件。

    返回 `(事件类型, 说明)`；认不出返回 `None`。
    一轮最多记一次——一句话里既有告白又有送礼，也只算一次，不叠buff。
    """
    if not text:
        return None
    for kind, desc, pattern in _EVENT_RULES:
        for match in pattern.finditer(text):
            # 否定语境不算事件：看匹配起点前一个字
            prev = text[match.start() - 1] if match.start() > 0 else ""
            if prev and prev in _NEGATORS:
                continue
            return kind, desc
    return None


def kinds() -> list[str]:
    """全部事件类型（供测试与文档核对，不影响运行逻辑）。"""
    return [kind for kind, _, _ in _EVENT_RULES]
